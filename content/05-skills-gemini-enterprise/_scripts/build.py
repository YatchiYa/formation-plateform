#!/usr/bin/env python3
"""Validate every skill, then build upload-ready files and the catalog.

  python3 scripts/build.py          # validate + build dist/ + CATALOG.md + skills-navigator
  python3 scripts/build.py --check  # validate only (safe to run in parallel)
"""
import re, sys, shutil, zipfile
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
DIST = ROOT / "dist"
NAV = SKILLS / "17-ai-adoption" / "skills-navigator"
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SECTIONS = ["When to use", "Inputs", "Sources", "Workflow", "Output format", "Quality checks", "Guardrails"]
MAX_BODY_LINES = 250


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        return None, None, text
    return yaml.safe_load(m.group(1)), m.group(2), m.group(1)


def check(path, names):
    errs, folder = [], path.parent.name
    meta, body, raw = parse(path)
    if meta is None:
        return ["missing or malformed YAML frontmatter"]
    if set(meta) != {"name", "description"}:
        errs.append(f"frontmatter keys must be exactly name+description, got {sorted(meta)}")
    name, desc = str(meta.get("name", "")), str(meta.get("description", ""))
    if not NAME_RE.match(name) or len(name) > 64:
        errs.append(f"invalid name '{name}'")
    if name != folder:
        errs.append(f"name '{name}' != folder '{folder}'")
    if not re.search(r'^description: ".*"$', raw, re.M):
        errs.append("description must be one double-quoted line")
    if not 200 <= len(desc) <= 1024:
        errs.append(f"description length {len(desc)} not in 200..1024")
    if "Use " not in desc or "Triggers" not in desc:
        errs.append("description needs 'Use when/whenever…' and a 'Triggers -' list")
    lines = body.strip().splitlines()
    if len(lines) > MAX_BODY_LINES:
        errs.append(f"body {len(lines)} lines > {MAX_BODY_LINES}")
    h2 = re.findall(r"^## (.+)$", re.sub(r"^```.*?^```", "", body, flags=re.S | re.M), re.M)  # ignore templates
    core = [h for h in h2 if h in SECTIONS]
    if core != SECTIONS:
        errs.append(f"H2 sections must include, in order, {SECTIONS}; got {h2}")
    if "Not for:" not in body:
        errs.append("'When to use' needs a 'Not for:' routing line")
    if "If a source is not connected" not in body:
        errs.append("'Sources' must end with the not-connected fallback line")
    for bad in ("TODO", "TBD", "lorem", "Lorem"):
        if bad in body:
            errs.append(f"placeholder text '{bad}'")
    for ref in re.findall(r"`([a-z0-9]+(?:-[a-z0-9]+)+)`", body):
        if ref not in names and ref != name and "--check" not in sys.argv:
            errs.append(f"references unknown skill `{ref}`")  # skipped in --check: siblings may not exist yet
    return errs


def first_sentence(desc):
    return re.split(r"(?<=\.)\s", desc, maxsplit=1)[0]


def write_navigator(skills):
    rows, current = [], None
    for path, meta in skills:
        if meta["name"] == "skills-navigator":
            continue
        domain = path.parent.parent.name
        if domain != current:
            rows.append(f"\n### {domain[3:].replace('-', ' ').title()}")
            current = domain
        rows.append(f"- `{meta['name']}` — {first_sentence(meta['description'])}")
    NAV.mkdir(parents=True, exist_ok=True)
    (NAV / "SKILL.md").write_text(f'''---
name: skills-navigator
description: "Recommends which skill from the Company Gemini Enterprise skill library fits a task, explains what each skill does and suggests skill chains for multi-step workflows. Use whenever the user asks which skill to use, what skills exist, what Gemini can help with in their job, or describes a task without knowing which skill applies. Triggers - which skill, what skills, list skills, what can you do for me, help me choose, quel skill, quelles compétences, quels skills existent, que peux-tu faire pour moi, catalogue des skills."
---

# Skills navigator

Helps teammates find the right skill among the {len(skills) - 1} skills of the library and chain them for bigger workflows.
This file is generated by `scripts/build.py`. Do not edit it by hand.

## When to use
- The user asks what skills exist or which one fits their task.
- The user describes a job or role and wants to know how Gemini can help.
- A task needs several skills in sequence.
- Not for: doing the task itself. Once the skill is chosen, invoke it with `/` or `@`.

## Inputs
- The task, role or question (required). If it is vague, ask one question about the expected deliverable.

## Sources
- The catalog below is the only source. Recommend only skills that are listed in it.
- If a source is not connected or returns nothing, say so in one line and continue with what you have. Never announce a search without giving its result in the same answer.

## Workflow
1. Restate the task in one line.
2. Choose the 1–3 best matching skills from the catalog. Match on the deliverable first, then on the domain.
3. If the task has several steps, propose a chain, for example `meeting-notes-to-actions` → `email-reply-drafter`.
4. For each recommendation, give the exact invocation (`/skill-name`) and a ready-to-paste first prompt.
5. If nothing fits, say so and suggest `skill-builder` to create a new skill.

## Output format
```markdown
**Best fit:** `/<skill-name>` — <why, one line>
**Try:** "<ready-to-paste prompt>"
**Also useful:** `/<skill>` (<when>) · `/<skill>` (<when>)
**Chain (if multi-step):** `<skill>` → `<skill>` → `<skill>`
```

## Quality checks
- Every recommended skill name exists in the catalog below.
- The ready-to-paste prompt contains the user's real context.

## Guardrails
- Never claim that a skill exists if it is not in the catalog.

## Catalog
{chr(10).join(rows)}
''', encoding="utf-8")


def main():
    only_check = "--check" in sys.argv
    paths = sorted(SKILLS.glob("*/*/SKILL.md"))
    if not only_check:
        names = {p.parent.name for p in paths} | {"skills-navigator"}
        write_navigator([(p, parse(p)[0]) for p in paths if parse(p)[0]])
        paths = sorted(SKILLS.glob("*/*/SKILL.md"))
    names = [p.parent.name for p in paths]
    dupes = {n for n in names if names.count(n) > 1}
    failed = 0
    for p in paths:
        errs = check(p, set(names)) + ([f"duplicate name {p.parent.name}"] if p.parent.name in dupes else [])
        for e in errs:
            print(f"FAIL {p.relative_to(ROOT)}: {e}")
        failed += bool(errs)
    print(f"{len(paths)} skills, {failed} failing")
    if failed or only_check:
        sys.exit(1 if failed else 0)

    shutil.rmtree(DIST, ignore_errors=True)
    catalog = ["# Catalog\n", f"{len(paths)} skills. Generated by `scripts/build.py`.\n"]
    current = None
    for p in paths:
        meta, body, _ = parse(p)
        domain = p.parent.parent.name
        if domain != current:
            catalog.append(f"\n## {domain}\n\n| Skill | What it does |\n|---|---|")
            current = domain
        catalog.append(f"| [`{meta['name']}`](skills/{domain}/{meta['name']}/SKILL.md) | {first_sentence(meta['description'])} |")
        for kind in ("md", "zip"):
            (DIST / kind / domain).mkdir(parents=True, exist_ok=True)
        shutil.copy(p, DIST / "md" / domain / f"{meta['name']}.md")
        with zipfile.ZipFile(DIST / "zip" / domain / f"{meta['name']}.zip", "w", zipfile.ZIP_DEFLATED) as z:
            z.write(p, "SKILL.md")  # Gemini Enterprise requires SKILL.md at the zip root
    with zipfile.ZipFile(DIST / "all-skills-md.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted((DIST / "md").rglob("*.md")):
            z.write(f, f.relative_to(DIST / "md"))
    (ROOT / "CATALOG.md").write_text("\n".join(catalog) + "\n", encoding="utf-8")
    print(f"built dist/md, dist/zip, dist/all-skills-md.zip and CATALOG.md")


if __name__ == "__main__":
    main()
